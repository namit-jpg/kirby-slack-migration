"""Target-workspace app: recreate channels, members, messages, threads, reactions, pins, files.

Identity is the email address. A message is posted with its author's own user token, so it
shows up under their real name and avatar with no APP badge. Authors who haven't joined or
authorized yet are handled per ``ImportOptions.mode``:

* ``strict``      stop the channel at that author's first message, so channel order stays
                  exactly as it was. The next run continues from that point.
* ``skip``        post everything possible now. Delayed messages land later, out of order.
* ``impersonate`` post them now through the bot with the author's name and avatar. The
                  message is marked APP, so this goes against the "really sent by the user" goal.

Progress is saved after every message in target/state.json (old ts -> new ts), so a run
can be interrupted and resumed, and repeating it is how a delta migration works.
"""

from __future__ import annotations

import logging
import os
import time
from dataclasses import dataclass, field
from decimal import Decimal
from pathlib import Path
from typing import Any, Callable

from slack_sdk.errors import SlackApiError

from .slack import ClientFactory, error_code, format_date, make_client, paginate, today
from .store import Store
from .transform import Mapper

log = logging.getLogger(__name__)

# Real conversation content. Everything else (joins, topic changes, pins...) is either
# regenerated by Slack itself or is noise.
IMPORTABLE_SUBTYPES = {None, "thread_broadcast", "file_share", "me_message", "bot_message"}

POSTED, IGNORED = "posted", "ignored"
WAIT = "wait"


class MigrationError(RuntimeError):
    pass


@dataclass
class ImportOptions:
    mode: str = "strict"  # strict | skip | impersonate
    channels: set[str] | None = None  # old channel names; None = all
    dry_run: bool = False
    stamp_dates: bool = False
    neutralize_broadcasts: bool = True
    archive: bool = True
    post_interval: float = 1.1  # chat.postMessage allows ~1 msg/sec per channel
    never_joining: set[str] = field(default_factory=set)  # emails that will never exist in target
    departed: str = "impersonate"  # deactivated/never-joining authors: impersonate | drop | wait
    team_id: str | None = None  # target workspace, required with Enterprise Grid org-level tokens
    general_as_channel: bool = False  # recreate the default channel by name instead of using the target's
    invite_members: bool = True  # invite all original members, not just the people who post
    rename: dict[str, str] = field(default_factory=dict)  # old channel name -> name in the target


@dataclass
class Poster:
    kind: str  # "user" | "bot"
    client: Any
    email: str | None = None
    username: str | None = None
    icon_url: str | None = None


class Importer:
    def __init__(
        self,
        store: Store,
        options: ImportOptions | None = None,
        client_factory: ClientFactory = make_client,
        sleep: Callable[[float], None] = time.sleep,
    ):
        self.store = store
        self.opts = options or ImportOptions()
        self.client_factory = client_factory
        self.sleep = sleep

        self.users = store.load_users()
        self.channels = store.load_channels()
        self.tokens = store.load_tokens()
        self.state = store.load_state()

        bot_token = os.environ.get("TARGET_BOT_TOKEN") or (self.tokens.get("bot") or {}).get("token")
        self.bot = client_factory(bot_token) if bot_token else None
        self.bot_user_id: str | None = None

        self.email_by_old: dict[str, str] = {u["id"]: u["email"] for u in self.users.values() if u.get("email")}
        self.new_by_email: dict[str, str] = {}
        self.email_by_new: dict[str, str] = {}
        self._clients: dict[str, Any] = {}
        self._dry_counter = 0
        self._announced: set[str] = set()
        self.team = {"team_id": self.opts.team_id} if self.opts.team_id else {}

    # ==== setup ====================================================================

    def connect(self) -> None:
        """Map emails to target user IDs and check which user tokens still work."""
        valid: dict[str, Any] = {}
        for email, rec in self.tokens["users"].items():
            client = self.client_factory(rec["token"])
            try:
                client.auth_test()
                valid[email] = client
            except SlackApiError as exc:
                log.warning("Token for %s unusable (%s); they need to authorize again", email, error_code(exc))
        self._clients = valid

        reader = self.bot or next(iter(valid.values()), None)
        if reader is None:
            raise MigrationError("No target tokens. Run `serve-oauth` and authorize at least one user first.")
        for u in paginate(reader.users_list, "members", limit=200, **self.team):
            email = ((u.get("profile") or {}).get("email") or "").strip().lower()
            if email and not u.get("deleted") and not u.get("is_bot"):
                self.new_by_email[email] = u["id"]
        self.email_by_new = {v: k for k, v in self.new_by_email.items()}
        if self.bot:
            self.bot_user_id = self.bot.auth_test().get("user_id")

    def user_client(self, email: str | None):
        if email and email in self.new_by_email:
            return self._clients.get(email)
        return None

    def new_user_id(self, old_user_id: str | None) -> str | None:
        return self.new_by_email.get(self.email_by_old.get(old_user_id or "", ""))

    def mapper(self) -> Mapper:
        names = {uid: _display_name(u) for uid, u in self.users.items()}
        user_ids = {old: new for old in self.users if (new := self.new_user_id(old))}
        channel_ids = {
            old: st["new_id"] for old, st in self.state["channels"].items() if st.get("new_id")
        }
        channel_names = {cid: c["name"] for cid, c in self.channels.items()}
        return Mapper(user_ids, names, channel_ids, channel_names, self.opts.neutralize_broadcasts)

    def selected_channels(self) -> list[dict]:
        chans = [c for c in self.channels.values() if c.get("exported")]
        if self.opts.channels:
            chans = [c for c in chans if c["name"] in self.opts.channels]
        # general first: everyone is in it, so it never waits on channel creation.
        return sorted(chans, key=lambda c: (not c.get("is_general"), c.get("created") or 0, c["name"]))

    # ==== run ======================================================================

    def run(self) -> None:
        self.connect()
        chans = self.selected_channels()

        # Create every channel before posting anything, so #channel mentions in early
        # messages can link to channels that come later in the run.
        ready = []
        for ch in chans:
            cst = self.ensure_channel(ch)
            if cst:
                self.sync_members(ch, cst)
                ready.append((ch, cst))
            self.save()

        mapper = self.mapper()
        for ch, cst in ready:
            self.import_channel(ch, cst, mapper)
        self.save()
        log.info("Import pass finished. Run `status` to see what's still waiting.")

    def save(self) -> None:
        if not self.opts.dry_run:
            self.store.save_state(self.state)

    # ==== channels =================================================================

    def channel_state(self, ch: dict) -> dict:
        return self.state["channels"].setdefault(
            ch["id"], {"name": ch["name"], "new_id": None, "members": [], "temp_members": []}
        )

    def ensure_channel(self, ch: dict) -> dict | None:
        cst = self.channel_state(ch)
        if cst["new_id"]:
            return cst

        if ch.get("is_general") and not self.opts.general_as_channel:
            cst["new_id"] = self._general_channel_id()
            cst["general"] = True
            log.info("#%s -> existing default channel %s", ch["name"], cst["new_id"])
            return cst

        creator = self._pick_creator(ch)
        if not creator:
            self._announce(ch["id"] + ":create", "#%s waits: none of its members has authorized yet", ch["name"])
            return None
        client = self.user_client(creator)
        new_id = self._create_channel(client, ch)
        cst["new_id"] = new_id
        cst["created_by"] = creator
        creator_new = self.new_by_email[creator]
        cst["members"].append(creator_new)
        if not self._was_member(ch, creator):
            cst["temp_members"].append(creator_new)

        if not self.opts.dry_run:
            for field_name, method in (("topic", client.conversations_setTopic), ("purpose", client.conversations_setPurpose)):
                if ch.get(field_name):
                    try:
                        method(channel=new_id, **{field_name: self.mapper().text(ch[field_name])})
                    except SlackApiError as exc:
                        log.warning("#%s: could not set %s (%s)", ch["name"], field_name, error_code(exc))
        log.info("#%s created as #%s (%s) by %s", ch["name"], self.opts.rename.get(ch["name"], ch["name"]), new_id, creator)
        return cst

    def _pick_creator(self, ch: dict) -> str | None:
        # Prefer the original creator, then any original member, so the channel's
        # membership doesn't pick up someone who was never in it.
        candidates = [self.email_by_old.get(ch.get("creator") or "")]
        candidates += [self.email_by_old.get(m) for m in ch.get("members") or []]
        candidates += [self.tokens.get("installer_email")] + sorted(self._clients)
        return next((e for e in candidates if self.user_client(e)), None)

    def _was_member(self, ch: dict, email: str) -> bool:
        return any(self.email_by_old.get(m) == email for m in ch.get("members") or [])

    def _create_channel(self, client, ch: dict) -> str:
        name = self.opts.rename.get(ch["name"], ch["name"])
        if self.opts.dry_run:
            return f"DRY-{ch['id']}"
        try:
            return client.conversations_create(name=name, is_private=ch["is_private"], **self.team)["channel"]["id"]
        except SlackApiError as exc:
            if error_code(exc) != "name_taken":
                raise
        for existing in paginate(
            client.conversations_list, "channels", types="public_channel,private_channel", exclude_archived=False, limit=200, **self.team
        ):
            if existing["name"] == name:
                if not existing.get("is_member") and not existing.get("is_private"):
                    client.conversations_join(channel=existing["id"])
                log.info("#%s already exists in target; reusing %s", name, existing["id"])
                return existing["id"]
        raise MigrationError(f"#{name} exists in the target but its creator can't see it")

    def _general_channel_id(self) -> str:
        reader = self.bot or next(iter(self._clients.values()))
        for c in paginate(reader.conversations_list, "channels", types="public_channel", limit=200, **self.team):
            if c.get("is_general"):
                return c["id"]
        raise MigrationError("Could not find the target workspace's default channel")

    def _inviter(self, cst: dict):
        for new_id in cst["members"]:
            client = self.user_client(self.email_by_new.get(new_id))
            if client:
                return client
        return None

    def sync_members(self, ch: dict, cst: dict) -> None:
        """Invite every original member that already exists in the target workspace."""
        if cst.get("general") or not self.opts.invite_members:
            return
        wanted = [n for m in ch.get("members") or [] if (n := self.new_user_id(m)) and n not in cst["members"]]
        inviter = self._inviter(cst)
        if not wanted or not inviter:
            return
        if not self.opts.dry_run:
            for i in range(0, len(wanted), 500):
                batch = wanted[i : i + 500]
                try:
                    resp = inviter.conversations_invite(channel=cst["new_id"], users=",".join(batch), force=True)
                    for err in resp.get("errors") or []:
                        if err.get("error") not in {"already_in_channel", "cant_invite_self"}:
                            log.warning("#%s: invite %s failed (%s)", ch["name"], err.get("user"), err.get("error"))
                except SlackApiError as exc:
                    if error_code(exc) not in {"already_in_channel", "cant_invite_self"}:
                        raise
        cst["members"].extend(wanted)
        log.info("#%s: %d member(s) added", ch["name"], len(wanted))

    def ensure_member(self, ch: dict, cst: dict, poster: Poster) -> bool:
        if cst.get("general"):
            return True
        if poster.kind == "bot":
            if not ch["is_private"]:
                return True  # chat:write.public
            new_id = self.bot_user_id
        else:
            new_id = self.new_by_email[poster.email]
        if not new_id:
            return False
        if new_id in cst["members"]:
            return True

        if not self.opts.dry_run:
            if ch["is_private"]:
                inviter = self._inviter(cst)
                if not inviter:
                    return False
                inviter.conversations_invite(channel=cst["new_id"], users=new_id, force=True)
            else:
                poster.client.conversations_join(channel=cst["new_id"])
        cst["members"].append(new_id)
        if poster.kind == "bot" or not self._was_member(ch, poster.email):
            cst["temp_members"].append(new_id)
        return True

    # ==== messages =================================================================

    def import_channel(self, ch: dict, cst: dict, mapper: Mapper) -> None:
        msgs = self.store.load_messages(ch["id"])
        posted: dict[str, dict] = self.state["messages"].setdefault(ch["id"], {})
        ordered = sorted(msgs.values(), key=lambda m: Decimal(m["ts"]))

        # Reactions/pins from people who authorized after their message was posted.
        for m in ordered:
            rec = posted.get(m["ts"])
            if rec and rec["status"] == POSTED:
                self.sync_extras(ch, cst, m, rec)

        cst.pop("blocked_on", None)
        new_count = 0
        for m in ordered:
            if m["ts"] in posted:
                continue
            outcome = self.import_message(ch, cst, m, msgs, posted, mapper)
            if outcome == POSTED:
                new_count += 1
            elif outcome == WAIT and self.opts.mode == "strict":
                break

        waiting = sum(1 for m in ordered if m["ts"] not in posted and m.get("subtype") in IMPORTABLE_SUBTYPES)
        cst["waiting"] = waiting
        log.info("#%s: %d posted this run, %d waiting", ch["name"], new_count, waiting)
        if blocked := cst.get("blocked_on"):
            log.info(
                "#%s paused at %s message by %s (%s)",
                ch["name"], blocked["date"], blocked["author"], blocked["reason"],
            )

        if waiting == 0 and ch.get("is_archived") and self.opts.archive and not cst.get("archived"):
            if not self.opts.dry_run:
                self._inviter(cst).conversations_archive(channel=cst["new_id"])
            cst["archived"] = True
            log.info("#%s archived (it was archived in the source)", ch["name"])
        self.save()

    def import_message(self, ch, cst, m: dict, msgs: dict, posted: dict, mapper: Mapper) -> str:
        ts = m["ts"]
        subtype = m.get("subtype")
        if subtype not in IMPORTABLE_SUBTYPES:
            posted[ts] = {"status": IGNORED, "reason": subtype}
            return IGNORED

        poster, verdict = self.resolve_poster(m)
        if verdict == IGNORED:
            posted[ts] = {"status": IGNORED, "reason": "author-dropped"}
            return IGNORED
        if poster is None:
            self._block(cst, m, "has not joined/authorized yet")
            return WAIT

        thread_ts = None
        parent_ts = m.get("thread_ts")
        if parent_ts and parent_ts != ts:
            parent = posted.get(parent_ts)
            if parent and parent["status"] == POSTED and parent.get("new_ts"):
                thread_ts = parent["new_ts"]
            elif parent is None and parent_ts in msgs:
                self._block(cst, m, "its thread parent is still waiting")
                return WAIT
            # else: parent was deleted / not migrated; post the reply at top level.

        if not self.ensure_member(ch, cst, poster):
            self._block(cst, m, "could not be added to the private channel")
            return WAIT

        new_ts = self.post(ch, cst, m, poster, thread_ts, mapper)
        posted[ts] = {"status": POSTED, "new_ts": new_ts, "by": poster.email or f"bot:{poster.username}"}
        self.save()
        self.sync_extras(ch, cst, m, posted[ts])
        self.sleep(self.opts.post_interval)
        return POSTED

    def _block(self, cst: dict, m: dict, reason: str) -> None:
        cst.setdefault(
            "blocked_on",
            {
                "ts": m["ts"],
                "date": format_date(m["ts"]),
                "author": self.email_by_old.get(m.get("user") or "") or m.get("user") or "?",
                "reason": reason,
            },
        )

    def resolve_poster(self, m: dict) -> tuple[Poster | None, str]:
        uid = m.get("user")
        if m.get("subtype") == "bot_message" or (not uid and m.get("bot_id")):
            bp = m.get("bot_profile") or {}
            icon = (m.get("icons") or {}).get("image_72") or (bp.get("icons") or {}).get("image_72")
            return self._bot_poster(m.get("username") or bp.get("name") or "bot", icon)

        user = self.users.get(uid or "") or {}
        email = user.get("email")
        client = self.user_client(email)
        if client:
            return Poster("user", client, email=email), POSTED

        # Deactivated in the source but present in the target: they can still authorize.
        gone = user.get("deleted") and email not in self.new_by_email
        departed = not email or gone or email in self.opts.never_joining
        if departed and self.opts.departed == "drop":
            return None, IGNORED
        if (departed and self.opts.departed == "impersonate") or self.opts.mode == "impersonate":
            return self._bot_poster(_display_name(user) or uid or "unknown", user.get("image"))
        return None, WAIT

    def _bot_poster(self, username: str, icon_url: str | None) -> tuple[Poster | None, str]:
        if not self.bot:
            self._announce("nobot", "No bot token, so bot/departed-user messages wait (install the app via serve-oauth)")
            return None, WAIT
        return Poster("bot", self.bot, username=username, icon_url=icon_url), POSTED

    def post(self, ch, cst, m: dict, poster: Poster, thread_ts: str | None, mapper: Mapper) -> str | None:
        channel = cst["new_id"]
        text = mapper.text(m.get("text"))
        blocks = mapper.blocks(m.get("blocks"))

        files = m.get("files") or []
        local = [f for f in files if f.get("_local_path")]
        lost = [f for f in files if not f.get("_local_path")]
        notes = [f"📎 _{f.get('name') or 'file'} (not migrated)_" for f in lost]
        if self.opts.stamp_dates:
            notes.append(f"_Originally sent {format_date(m['ts'], with_time=True)}_")
        if notes:
            text, blocks = _append_note(text, blocks, "\n".join(notes))

        if self.opts.dry_run:
            self._dry_counter += 1
            log.info("[dry-run] #%s %s %s: %s", ch["name"], format_date(m["ts"]), poster.email or poster.username, text[:80])
            return f"{self._dry_counter}.000000"

        if local:
            return self._upload(poster.client, channel, local, text, thread_ts)

        if m.get("subtype") == "me_message" and poster.kind == "user" and not thread_ts:
            return poster.client.chat_meMessage(channel=channel, text=text)["ts"]

        kwargs: dict[str, Any] = {"channel": channel, "text": text or " "}
        if thread_ts:
            kwargs["thread_ts"] = thread_ts
            if m.get("subtype") == "thread_broadcast":
                kwargs["reply_broadcast"] = True
        if poster.kind == "bot":
            kwargs["username"] = poster.username
            if poster.icon_url:
                kwargs["icon_url"] = poster.icon_url
            if m.get("attachments") and m.get("subtype") == "bot_message":
                kwargs["attachments"] = m["attachments"]
        try:
            return poster.client.chat_postMessage(**kwargs, **({"blocks": blocks} if blocks else {}))["ts"]
        except SlackApiError as exc:
            if not blocks or error_code(exc) not in {"invalid_blocks", "invalid_blocks_format"}:
                raise
            log.warning("#%s %s: blocks rejected, posting text only", ch["name"], m["ts"])
            return poster.client.chat_postMessage(**kwargs)["ts"]

    def _upload(self, client, channel: str, files: list[dict], text: str, thread_ts: str | None) -> str | None:
        uploads = [
            {
                "file": str(self.store.export_dir / f["_local_path"]),
                "filename": f.get("name") or Path(f["_local_path"]).name,
                "title": f.get("title") or f.get("name"),
            }
            for f in files
        ]
        kwargs: dict[str, Any] = {"channel": channel, "file_uploads": uploads}
        if text:
            kwargs["initial_comment"] = text
        if thread_ts:
            kwargs["thread_ts"] = thread_ts
        resp = client.files_upload_v2(**kwargs)
        uploaded = resp.get("files") or ([resp["file"]] if resp.get("file") else [])
        if not uploaded:
            return None
        # File shares are attached asynchronously; poll until Slack reports the message ts.
        for _ in range(15):
            info = client.files_info(file=uploaded[0]["id"])["file"]
            for scope in ("public", "private"):
                entries = ((info.get("shares") or {}).get(scope) or {}).get(channel)
                if entries:
                    return max((e["ts"] for e in entries), key=Decimal)
            self.sleep(1.0)
        log.warning("Uploaded %s but Slack never reported the message ts", uploaded[0]["id"])
        return None

    # ==== reactions & pins =========================================================

    def sync_extras(self, ch: dict, cst: dict, m: dict, rec: dict) -> None:
        new_ts = rec.get("new_ts")
        if not new_ts or self.opts.dry_run:
            return
        done = rec.setdefault("reactions", {})
        for reaction in m.get("reactions") or []:
            name = reaction["name"]
            seen = done.setdefault(name, [])
            for uid in reaction.get("users") or []:
                email = self.email_by_old.get(uid)
                client = self.user_client(email)
                if not client or email in seen:
                    continue
                if not self.ensure_member(ch, cst, Poster("user", client, email=email)):
                    continue
                try:
                    client.reactions_add(channel=cst["new_id"], timestamp=new_ts, name=name)
                except SlackApiError as exc:
                    code = error_code(exc)
                    if code != "already_reacted":
                        # e.g. invalid_name for a custom emoji that doesn't exist in the target.
                        log.warning("#%s: reaction :%s: by %s failed (%s)", ch["name"], name, email, code)
                seen.append(email)

        if m.get("_pinned") and not rec.get("pinned"):
            client = self.user_client(rec.get("by")) or self._inviter(cst)
            if client:
                try:
                    client.pins_add(channel=cst["new_id"], timestamp=new_ts)
                except SlackApiError as exc:
                    if error_code(exc) != "already_pinned":
                        log.warning("#%s: pin failed (%s)", ch["name"], error_code(exc))
                rec["pinned"] = True

    # ==== cleanup & profiles =======================================================

    def leave_temp_members(self) -> None:
        """Remove people who were added only so they could post (or create the channel)."""
        self.connect()
        for ch in self.selected_channels():
            cst = self.state["channels"].get(ch["id"])
            if not cst or not cst.get("new_id") or cst.get("archived"):
                continue
            for new_id in list(cst.get("temp_members") or []):
                if new_id == self.bot_user_id:
                    client = self.bot
                else:
                    client = self.user_client(self.email_by_new.get(new_id))
                if not client:
                    continue
                try:
                    client.conversations_leave(channel=cst["new_id"])
                except SlackApiError as exc:
                    log.warning("#%s: %s could not leave (%s)", ch["name"], new_id, error_code(exc))
                    continue
                cst["temp_members"].remove(new_id)
                cst["members"].remove(new_id)
                log.info("#%s: %s left", ch["name"], self.email_by_new.get(new_id, new_id))
        self.save()

    def sync_profiles(self, force: bool = False) -> None:
        self.connect()
        by_email = {u["email"]: u for u in self.users.values() if u.get("email")}
        for email, client in self._clients.items():
            src = by_email.get(email)
            if not src or (self.state["profiles"].get(email) and not force):
                continue
            fields = ("first_name", "last_name", "display_name", "title", "phone", "pronouns")
            profile = {k: src[k] for k in fields if src.get(k)}
            try:
                if profile:
                    client.users_profile_set(profile=profile)
                if src.get("_avatar_path"):
                    client.users_setPhoto(image=str(self.store.export_dir / src["_avatar_path"]))
            except SlackApiError as exc:
                log.warning("Profile for %s: %s", email, error_code(exc))
                continue
            self.state["profiles"][email] = today()
            log.info("Profile synced for %s", email)
        self.save()

    def _announce(self, key: str, msg: str, *args) -> None:
        if key not in self._announced:
            self._announced.add(key)
            log.warning(msg, *args)


def _display_name(user: dict) -> str:
    return user.get("display_name") or user.get("real_name") or user.get("name") or ""


def _append_note(text: str, blocks: list[dict] | None, note: str) -> tuple[str, list[dict] | None]:
    text = f"{text}\n{note}" if text else note
    if blocks:
        blocks = blocks + [{"type": "context", "elements": [{"type": "mrkdwn", "text": note}]}]
    return text, blocks
